/**
 * 生成一道圣旨。
 * @param name 受封者，可为空
 */
export function randomEdict(name = ''): string {
  const who = name.trim() || '卿'
  const pick = <T>(a: readonly T[]) => a[Math.floor(Math.random() * a.length)]

  const body =
    `${pick(SURVEY)}。今有${who}，${pick(DEED)}，` +
    `${pick(GRANT)}。${pick(REWARD)}。`

  return `${pick(OPENERS)}${body}\n\n${pick(EXHORT)}。${pick(CLOSERS)}`
}

